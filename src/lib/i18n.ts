export type Lang = 'en' | 'fr'
export const LANGS: Record<Lang, string> = { en: 'English', fr: 'Français' }

const all: Record<Lang, Strings> = { en, fr }

let systemLocale = navigator.language || 'en'

/** The webview's own language follows the app bundle, so the system locale comes from Rust */
export function setSystemLocale(locale: string) {
  systemLocale = locale
}

export function systemLang(): Lang {
  return systemLocale.toLowerCase().startsWith('fr') ? 'fr' : 'en'
}

export function strings(lang: Lang): Strings {
  return all[lang]
}

export type { Strings }
